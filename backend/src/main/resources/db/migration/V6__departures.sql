-- Salidas de ascensor (#114, ADR 0007): una franja es una salida de ~2 min. Se generan perezosamente al consultar
-- la ventana de reserva, así que la unicidad (ascensor + instante) es lo que hace idempotente la generación.
-- departure_at va en UTC (ADR 0010). capacity se copia de app_config (turn_capacity) al generar.
CREATE TABLE departure (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    elevator_code VARCHAR(8)               NOT NULL REFERENCES elevator (code),
    departure_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    capacity      INT                      NOT NULL CHECK (capacity > 0),
    status        VARCHAR(16)              NOT NULL CHECK (status IN ('SCHEDULED', 'CANCELLED')),
    CONSTRAINT uk_departure_elevator_at UNIQUE (elevator_code, departure_at)
);
