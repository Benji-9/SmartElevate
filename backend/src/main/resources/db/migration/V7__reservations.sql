-- Reservas de un lugar en una salida (#115, ADR 0007 y 0010).
-- Cupo atómico: el service toma un lock pesimista sobre la salida (SELECT ... FOR UPDATE) y además el
-- constraint único (departure_id, seat_number) impide que dos reservas tomen el mismo lugar aunque falle el lock.
-- seat_number es NULL cuando la reserva se cancela (#116): libera el lugar y los NULL no chocan en el único.
CREATE TABLE reservation (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id           UUID                     NOT NULL REFERENCES app_user (id),
    departure_id      BIGINT                   NOT NULL REFERENCES departure (id),
    seat_number       INT CHECK (seat_number > 0),
    origin_floor      INT                      NOT NULL,
    destination_floor INT                      NOT NULL,
    status            VARCHAR(16)              NOT NULL CHECK (status IN ('ACTIVE', 'CANCELLED')),
    created_at        TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_reservation_departure_seat UNIQUE (departure_id, seat_number)
);

CREATE INDEX ix_reservation_user ON reservation (user_id, created_at);
