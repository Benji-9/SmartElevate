-- Suspensiones por faltas (#231, turnos.md §5). Una fila por suspensión: la dispara la falta que completa
-- no_show_suspension_threshold dentro de no_show_suspension_window y dura no_show_suspension_duration.
-- Después de cada una el conteo arranca de cero: para la siguiente solo cuentan las faltas desde ends_at.
-- starts_at hoy coincide con trigger_fault_at (la suspensión rige desde esa falta); quedan separadas para poder
-- registrar otro inicio sin migrar. El único (user_id, trigger_fault_at) hace idempotente la creación.
CREATE TABLE no_show_suspension (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          UUID                     NOT NULL REFERENCES app_user (id),
    starts_at        TIMESTAMP WITH TIME ZONE NOT NULL,
    ends_at          TIMESTAMP WITH TIME ZONE NOT NULL,
    trigger_fault_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_no_show_suspension_trigger UNIQUE (user_id, trigger_fault_at),
    CONSTRAINT ck_no_show_suspension_range CHECK (ends_at > starts_at)
);
CREATE INDEX ix_no_show_suspension_user ON no_show_suspension (user_id, ends_at);
