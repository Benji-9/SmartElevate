-- Check-in con QR (#230, ADR 0008 y 0020, check-in-qr.md). Estados nuevos de la reserva:
--   USED     check-in a tiempo (en el ascensor de la reserva o en otro).
--   NO_SHOW  sin check-in a tiempo: lo marca el job de no-shows (#231) o un escaneo fuera de hora.
-- Las dos conservan el lugar (seat_number): son el registro de quién ocupaba qué lugar. Solo cancelar lo libera.
-- Cuando hay check-in ya cerró la ventana de reserva (check_in_opens_before <= booking_closes_before, lo valida
-- ConfigService), así que nadie más puede pedir ese lugar.
ALTER TABLE reservation DROP CONSTRAINT ck_reservation_status;
ALTER TABLE reservation ADD CONSTRAINT ck_reservation_status
    CHECK (status IN ('ACTIVE', 'CANCELLED', 'CANCELLED_LATE', 'USED', 'NO_SHOW'));
ALTER TABLE reservation DROP CONSTRAINT ck_reservation_seat_when_active;
ALTER TABLE reservation ADD CONSTRAINT ck_reservation_seat_unless_cancelled
    CHECK ((status IN ('CANCELLED', 'CANCELLED_LATE')) = (seat_number IS NULL));

-- Una lectura por reserva: el único sobre reservation_id es la red de seguridad del lock del service.
-- elevator_code es el ascensor escaneado (sale del token firmado); si difiere del de la reserva, es la diferencia
-- que mide el KPI de distribución. source sale del kiosco firmado en el token: SIMULATED = simulador de admin.
CREATE TABLE check_in (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reservation_id BIGINT                   NOT NULL REFERENCES reservation (id),
    outcome        VARCHAR(16)              NOT NULL CHECK (outcome IN ('ON_TIME', 'OTHER_ELEVATOR', 'LATE')),
    elevator_code  VARCHAR(8)               NOT NULL REFERENCES elevator (code),
    source         VARCHAR(16)              NOT NULL CHECK (source IN ('REAL', 'SIMULATED')),
    kiosk_id       UUID                     NOT NULL REFERENCES kiosk (id),
    checked_in_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_check_in_reservation UNIQUE (reservation_id)
);
